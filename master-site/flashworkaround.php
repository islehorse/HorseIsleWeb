<B>Advanced Shortcut Creation for Windows:</B> <BR>
If you would like to create a shortcut for a server for the above setup in windows, you can follow these steps.<BR><BR>
<LI>Right click on the "flashplayer_32_sa.exe" projector that you downloaded above -> Click "Create Shortcut"
<LI>Right click on this new icon "flashplayer_32_sa.exe Shortcut"   ->  Click "Properties"
<LI>Under General Tab - Rename the Icon to "HI2-Eternal" or similar.
<LI>Click Under Shortcut Tab - Scroll to the end of the Target: existing contents. (Do not edit/delete this!)
<LI>Add a space, and then the URL shown above for your desired server after the existing target contents.
<LI>For Example in "Target:" I have: C:\xxxxxxxx\flashplayer_32_sa.exe http://hi2.horseisle.com/client/HI2Client.swf?SERVER=216.98.148.87&PORT1=44344&PORT2=443&USER=Jor
<LI>You can add the &USER=name to the end like i have to save typing username at login.
<LI>Click "OK" at the bottom.  Now, you should be able to doubleclick that icon to save time :)
<LI>You can repeat process for any other servers you play on.
